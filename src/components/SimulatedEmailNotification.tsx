import React, { useState, useEffect } from 'react';
import { Mail, Check, Copy, X, Send } from 'lucide-react';
import { EmailNotification, subscribeToEmailDispatches } from '../services/apiService.ts';

interface SimulatedEmailNotificationProps {
  onAutofillOtp?: (otp: string) => void;
}

export const SimulatedEmailNotification: React.FC<SimulatedEmailNotificationProps> = ({
  onAutofillOtp,
}) => {
  const [notification, setNotification] = useState<EmailNotification | null>(null);
  const [copied, setCopied] = useState(false);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const unsubscribe = subscribeToEmailDispatches(email => {
      setNotification(email);
      setVisible(true);
      // Auto-hide after 15 seconds if not closed
      const timer = setTimeout(() => {
        setVisible(false);
      }, 15000);
      return () => clearTimeout(timer);
    });

    return () => unsubscribe();
  }, []);

  if (!visible || !notification) return null;

  const handleCopy = () => {
    navigator.clipboard?.writeText(notification.otpCode);
    setCopied(true);
    if (typeof window !== 'undefined') {
      window.dispatchEvent(
        new CustomEvent('safeconnect-autofill-otp', {
          detail: { otp: notification.otpCode },
        })
      );
    }
    if (onAutofillOtp) onAutofillOtp(notification.otpCode);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed top-20 right-4 z-50 max-w-sm w-full glass p-4 border border-[#27d3ff]/50 shadow-[0_10px_35px_rgba(0,0,0,0.8),0_0_25px_rgba(39,211,255,0.3)] rounded-2xl animate-rise text-white">
      <div className="flex items-start justify-between pb-2 border-b border-[#78aaff]/20">
        <div className="flex items-center gap-2">
          <div className="w-7 h-7 rounded-lg bg-[#27d3ff]/20 flex items-center justify-center text-[#27d3ff]">
            <Mail className="w-4 h-4" />
          </div>
          <div>
            <span className="text-xs font-bold block text-white">Gmail SMTP / PHPMailer</span>
            <span className="text-[10px] text-[#9fb0d6]">{notification.timestamp}</span>
          </div>
        </div>
        <button
          onClick={() => setVisible(false)}
          className="p-1 rounded-lg text-[#9fb0d6] hover:text-white"
        >
          <X className="w-4 h-4" />
        </button>
      </div>

      <div className="mt-2.5 text-xs">
        <p className="text-[11px] text-[#9fb0d6]">
          To: <strong className="text-white">{notification.recipientEmail}</strong>
        </p>
        <p className="font-semibold text-white mt-1 text-xs">{notification.subject}</p>

        {/* OTP Highlight */}
        <div className="my-2.5 p-2.5 rounded-xl bg-[#050b1f] border border-[#27d3ff]/40 flex items-center justify-between">
          <div>
            <span className="text-[10px] text-[#9fb0d6] block">Your One-Time Code:</span>
            <span className="font-mono text-xl font-extrabold text-[#27d3ff] tracking-widest">
              {notification.otpCode}
            </span>
          </div>

          <button
            onClick={handleCopy}
            className="btn py-1.5 px-3 text-xs font-semibold cursor-pointer shadow-none"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-300" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? 'Copied' : 'Auto-Fill'}</span>
          </button>
        </div>

        <p className="text-[10px] text-[#6479a6]">
          Generated by SafeConnect registration engine. Valid for 10 minutes.
        </p>
      </div>
    </div>
  );
};
